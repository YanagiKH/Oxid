def _balanced_input(body, match, opening):
    """Retain complete selector syntax, including multiline/nested attributes.

    This conservative lexical census is independent of the exact full-file pin.
    It does not interpret conditions or approve any new compile-time input.
    """
    closing = {ord('['): ord(']'), ord('('): ord(')'), ord('{'): ord('}')}
    stack = [closing[opening]]
    index = match.end()
    quoted = False
    escaped = False
    while index < len(body):
        value = body[index]
        index += 1
        if quoted:
            if escaped:
                escaped = False
            elif value == ord('\\'):
                escaped = True
            elif value == ord('"'):
                quoted = False
            continue
        if value == ord('"'):
            quoted = True
        elif value in closing:
            stack.append(closing[value])
        elif value in closing.values():
            require(stack and value == stack.pop(), 'unbalanced compile-time selector')
            if not stack:
                return body[match.start():index]
    raise ValueError('incomplete compile-time selector')


def source_directives(name, body):
    """Bind selectors/assets in addition to the inherited include/path census."""
    legacy = directives(body)
    attributes = tuple(_balanced_input(body, match, ord('['))
                       for match in re.finditer(rb'#\s*!?\s*\[', body))
    macros = tuple(_balanced_input(body, match, match.group()[-1])
                   for match in re.finditer(
                       rb'\b(?:include(?:_str|_bytes)?|cfg|env|option_env)\s*!\s*[({\[]', body))
    # Preserve complete C preprocessor logical lines, including continuations.
    preprocessors = tuple(match.group() for match in re.finditer(
        rb'(?m)^[ \t]*#[ \t]*[A-Za-z_][A-Za-z_0-9]*(?:[^\n]*\\\n)*[^\n]*(?:\n|$)', body))
    return {'legacy': legacy, 'attributes': attributes, 'macros': macros,
            'c_preprocessor': preprocessors,
            'build_script': body if name == 'build.rs' else None}


